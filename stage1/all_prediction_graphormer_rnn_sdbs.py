class RNNModel(nn.Module):
    def __init__(
        self,
        vocab_size: int,
        embedding_dim: int,
        hidden_dim: int,
        num_layers: int,
        dropout: float = 0.1,
    ):
        super().__init__()
        self.hidden_dim = hidden_dim
        self.num_layers = num_layers
        self.embedding = nn.Embedding(vocab_size, embedding_dim)
        self.rnn = nn.GRU(
            input_size=embedding_dim,
            hidden_size=hidden_dim,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0.0,
        )
        self.fc = nn.Linear(hidden_dim, vocab_size)

    def forward(self, x: torch.Tensor, hidden: Optional[torch.Tensor] = None):
        embedded = self.embedding(x)
        output, hidden = self.rnn(embedded, hidden)
        logits = self.fc(output)
        return logits, hidden

    def init_hidden(self, batch_size: int, device: torch.device) -> torch.Tensor:
        return torch.zeros(
            self.num_layers,
            batch_size,
            self.hidden_dim,
            device=device,
        )


def normalize_idx_to_token(idx_to_token: Dict) -> Dict[int, str]:
    return {int(k): v for k, v in idx_to_token.items()}


def detokenize_smiles(tokens: Sequence[str]) -> str:
    return "".join(tokens)


def sample_next_token(logits: torch.Tensor, temperature: float = 1.0, top_k: int = 0) -> int:
    if temperature <= 0:
        return torch.argmax(logits).item()

    logits = logits / temperature

    if top_k and top_k > 0:
        top_k = min(top_k, logits.size(-1))
        values, indices = torch.topk(logits, top_k)
        probs = torch.softmax(values, dim=-1)
        sampled_position = torch.multinomial(probs, num_samples=1).item()
        return indices[sampled_position].item()

    probs = torch.softmax(logits, dim=-1)
    return torch.multinomial(probs, num_samples=1).item()


def load_rnn_from_checkpoint(checkpoint_path: str, device: torch.device):
    checkpoint = torch.load(checkpoint_path, map_location=device)

    token_to_idx = checkpoint["token_to_idx"]
    idx_to_token = normalize_idx_to_token(checkpoint["idx_to_token"])

    embedding_dim = checkpoint["embedding_dim"]
    hidden_dim = checkpoint["hidden_dim"]
    num_layers = checkpoint["num_layers"]
    dropout = checkpoint.get("dropout", 0.1)

    model = RNNModel(
        vocab_size=len(token_to_idx),
        embedding_dim=embedding_dim,
        hidden_dim=hidden_dim,
        num_layers=num_layers,
        dropout=dropout,
    ).to(device)

    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()

    max_length = checkpoint.get("max_length", 200)
    return model, token_to_idx, idx_to_token, max_length


@torch.no_grad()
def generate_one_smiles(
    model: RNNModel,
    token_to_idx: Dict[str, int],
    idx_to_token: Dict[int, str],
    max_length: int,
    device: torch.device,
    temperature: float = 1.0,
    top_k: int = 30,
) -> Tuple[str, List[str]]:
    go_idx = token_to_idx["GO"]
    eos_idx = token_to_idx["EOS"]
    pad_idx = token_to_idx["PAD"]

    current_idx = go_idx
    hidden = model.init_hidden(1, device)
    generated_tokens: List[str] = []

    for _ in range(max_length):
        input_tensor = torch.tensor([[current_idx]], dtype=torch.long, device=device)
        logits, hidden = model(input_tensor, hidden)

        next_idx = sample_next_token(
            logits[0, -1],
            temperature=temperature,
            top_k=top_k,
        )

        if next_idx == eos_idx:
            break

        if next_idx in {go_idx, pad_idx}:
            continue

        token = idx_to_token[next_idx]
        generated_tokens.append(token)
        current_idx = next_idx

    return detokenize_smiles(generated_tokens), generated_tokens


def generate_many_smiles(
    model: RNNModel,
    token_to_idx: Dict[str, int],
    idx_to_token: Dict[int, str],
    max_length: int,
    device: torch.device,
    num_generate: int = 1000,
    temperature: float = 1.0,
    top_k: int = 30,
    valid_only: bool = False,
    unique_canonical: bool = False,
    max_attempt_factor: int = 20,
) -> pd.DataFrame:
    records = []
    seen_canonical = set()

    max_attempts = num_generate
    if valid_only or unique_canonical:
        max_attempts = num_generate * max_attempt_factor

    attempts = 0
    progress = tqdm(total=num_generate, desc="Generating SMILES")

    while len(records) < num_generate and attempts < max_attempts:
        attempts += 1
        smi, tokens = generate_one_smiles(
            model=model,
            token_to_idx=token_to_idx,
            idx_to_token=idx_to_token,
            max_length=max_length,
            device=device,
            temperature=temperature,
            top_k=top_k,
        )

        mol = Chem.MolFromSmiles(smi)
        valid = mol is not None
        canonical = Chem.MolToSmiles(mol, canonical=True) if valid else ""

        if valid_only and not valid:
            continue

        if unique_canonical:
            if not valid:
                continue
            if canonical in seen_canonical:
                continue
            seen_canonical.add(canonical)

        records.append(
            {
                "Generated_SMILES": smi,
                "Valid": valid,
                "Canonical_SMILES": canonical,
                "Token_Length": len(tokens),
                "Tokens": " ".join(tokens),
            }
        )
        progress.update(1)

    progress.close()

    if len(records) < num_generate:
        print(
            f"Warning: requested {num_generate} SMILES, "
            f"but only generated {len(records)} after {attempts} attempts."
        )

    return pd.DataFrame(records)



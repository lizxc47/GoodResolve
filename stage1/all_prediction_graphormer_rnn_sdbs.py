def set_seed(seed: int = 42) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def add_graphormer_local_to_path(local_pytorch_dir: str) -> None:
    local_pytorch_dir = os.path.abspath(local_pytorch_dir)
    if local_pytorch_dir not in sys.path:
        sys.path.insert(0, local_pytorch_dir)


def normalize_phase(phase: str) -> str:
    """Normalize phase labels for the current Graphormer-IR-inspired model."""
    p = str(phase).strip()
    low = " ".join(p.lower().split())

    mapping = {
        "kbr disc": "KBr",
        "kbr disk": "KBr",
        "kbr": "KBr",
        "nujol mull": "nujol mull",
        "liquid film": "liquid film",
    }

    return mapping.get(low, p)


def parse_target_indices(text: Optional[str]) -> Optional[List[int]]:
    if text is None or str(text).strip() == "":
        return None

    indices = []
    for part in str(text).split(","):
        part = part.strip()
        if not part:
            continue
        indices.append(int(part))
    return indices



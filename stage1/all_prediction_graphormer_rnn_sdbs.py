class CandidateGraphDataset(Dataset):
    def __init__(self, smiles_list: Sequence[str], phase: str, mol_to_features_fn, max_dist: int):
        self.items = []
        phase = normalize_phase(phase)

        # phase_to_id is imported later from graphormer_ir_local.
        from graphormer_ir_local import phase_to_id

        skipped = 0
        for i, smi in enumerate(smiles_list):
            graph = mol_to_features_fn(smi, max_dist=max_dist)
            if graph is None:
                skipped += 1
                continue
            self.items.append(
                {
                    "row_index": i,
                    "smiles": str(smi),
                    "phase": phase,
                    "phase_id": phase_to_id(phase),
                    "graph": graph,
                    "y": None,
                }
            )

        if skipped:
            print(f"Skipped {skipped} candidates that could not be converted to molecular graphs.")

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, idx: int) -> Dict:
        return self.items[idx]



def load_graphormer_forward_model(checkpoint_path: str, device: torch.device):
    from graphormer_ir_local import GraphormerIRLocal

    ckpt = torch.load(checkpoint_path, map_location="cpu")
    model_config = ckpt["model_config"]
    model = GraphormerIRLocal(**model_config).to(device)
    model.load_state_dict(ckpt["model_state_dict"], strict=True)
    model.eval()
    return model, ckpt


def infer_step_cm(spectrum_cols: Sequence[str]) -> float:
    try:
        values = np.array([float(str(c).replace("pred_", "").replace("true_", "")) for c in spectrum_cols])
        diffs = np.diff(values)
        if len(diffs) > 0:
            return float(np.median(np.abs(diffs)))
    except Exception:
        pass
    return 2.0


def gaussian_smooth_for_sis(
    spectra: torch.Tensor,
    std_dev_cm: float = 15.0,
    step_cm: float = 2.0,
    truncate: float = 5.0,
) -> torch.Tensor:
    if std_dev_cm <= 0:
        return spectra

    radius = max(1, int(math.ceil(truncate * std_dev_cm / step_cm)))
    offsets = torch.arange(
        -radius,
        radius + 1,
        device=spectra.device,
        dtype=spectra.dtype,
    ) * step_cm
    kernel = torch.exp(-0.5 * (offsets / std_dev_cm) ** 2).view(1, 1, -1)
    return torch.nn.functional.conv1d(spectra.unsqueeze(1), kernel, padding=radius).squeeze(1)


def sis_score_batch_graphormer_style(
    pred: torch.Tensor,
    target: torch.Tensor,
    eps: float = 1e-8,
    gaussian_std_cm: float = 15.0,
    step_cm: float = 2.0,
) -> torch.Tensor:
    """Graphormer-IR evaluation-style SIS with Gaussian smoothing."""
    valid_mask = torch.isfinite(pred) & torch.isfinite(target)
    pred = torch.where(valid_mask, pred, torch.zeros_like(pred))
    target = torch.where(valid_mask, target, torch.zeros_like(target))

    pred = torch.clamp(pred, min=1e-7, max=1.0)
    target = torch.clamp(target, min=1e-7, max=1.0)

    pred = pred / pred.max(dim=1, keepdim=True).values.clamp_min(eps)
    target = target / target.max(dim=1, keepdim=True).values.clamp_min(eps)

    pred_smooth = gaussian_smooth_for_sis(pred, std_dev_cm=gaussian_std_cm, step_cm=step_cm)
    target_smooth = gaussian_smooth_for_sis(target, std_dev_cm=gaussian_std_cm, step_cm=step_cm)

    pred_smooth = torch.where(valid_mask, pred_smooth, torch.zeros_like(pred_smooth))
    target_smooth = torch.where(valid_mask, target_smooth, torch.zeros_like(target_smooth))

    p = pred_smooth / pred_smooth.sum(dim=1, keepdim=True).clamp_min(eps)
    q = target_smooth / target_smooth.sum(dim=1, keepdim=True).clamp_min(eps)
    p = torch.clamp(p, min=eps)
    q = torch.clamp(q, min=eps)

    sid = p * torch.log(p / q) + q * torch.log(q / p)
    sid = torch.where(valid_mask, sid, torch.zeros_like(sid))
    sid = sid.sum(dim=1)
    return 1.0 / (1.0 + sid)


def make_amp_context(enabled: bool, device: torch.device):
    if enabled and device.type == "cuda":
        # torch.cuda.amp.autocast is used for compatibility with older torch versions.
        return torch.cuda.amp.autocast(enabled=True)
    return torch.cuda.amp.autocast(enabled=False)


@torch.no_grad()
def predict_candidates_with_graphormer(
    smiles_list: Sequence[str],
    phase: str,
    target_spectrum: np.ndarray,
    model,
    ckpt: Dict,
    device: torch.device,
    batch_size: int = 64,
    num_workers: int = 2,
    amp: bool = True,
    gaussian_std_cm: float = 15.0,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    from graphormer_ir_local import collate_graphs, mol_to_features, move_batch_to_device

    model_config = ckpt["model_config"]
    spectrum_cols = [str(c) for c in ckpt["spectrum_cols"]]
    max_dist = model_config.get("max_dist", 20)
    step_cm = infer_step_cm(spectrum_cols)

    dataset = CandidateGraphDataset(
        smiles_list=smiles_list,
        phase=phase,
        mol_to_features_fn=mol_to_features,
        max_dist=max_dist,
    )

    if len(dataset) == 0:
        return pd.DataFrame(columns=["SMILES", "SIS"]), pd.DataFrame()

    loader = DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
        collate_fn=lambda b: collate_graphs(b, max_dist=max_dist),
        drop_last=False,
    )

    target_tensor_base = torch.tensor(target_spectrum, dtype=torch.float32, device=device).view(1, -1)

    sis_rows: List[Dict] = []
    spectra_rows: List[Dict] = []
    max_sis = -float("inf")

    progress = tqdm(loader, desc=f"Predicting candidate IR | phase={phase}")

    for batch in progress:
        batch = move_batch_to_device(batch, device)

        with make_amp_context(amp, device):
            pred = model(batch)

        target_batch = target_tensor_base.repeat(pred.size(0), 1)
        sis_values = sis_score_batch_graphormer_style(
            pred=pred,
            target=target_batch,
            gaussian_std_cm=gaussian_std_cm,
            step_cm=step_cm,
        )

        pred_np = pred.detach().float().cpu().numpy()
        sis_np = sis_values.detach().float().cpu().numpy()

        batch_max = float(np.max(sis_np)) if len(sis_np) else max_sis
        if batch_max > max_sis:
            max_sis = batch_max
            progress.set_description(f"Predicting candidate IR | max SIS={max_sis:.4f}")

        for i in range(pred_np.shape[0]):
            smi = batch["smiles"][i]
            sis = float(sis_np[i])
            sis_rows.append({"SMILES": smi, "phase": normalize_phase(phase), "SIS": sis})

            row = {"SMILES": smi, "phase": normalize_phase(phase), "SIS": sis}
            for j, col in enumerate(spectrum_cols):
                row[f"pred_{col}"] = float(pred_np[i, j])
            spectra_rows.append(row)

    sis_df = pd.DataFrame(sis_rows)
    spectra_df = pd.DataFrame(spectra_rows)

    if len(sis_df):
        sis_df = sis_df.sort_values("SIS", ascending=False).reset_index(drop=True)
        sis_df.insert(0, "Rank", np.arange(1, len(sis_df) + 1))

    if len(spectra_df):
        spectra_df = spectra_df.sort_values("SIS", ascending=False).reset_index(drop=True)
        spectra_df.insert(0, "Rank", np.arange(1, len(spectra_df) + 1))

    return sis_df, spectra_df



def get_spectrum_cols_from_checkpoint(ckpt: Dict, df: pd.DataFrame) -> List[str]:
    if "spectrum_cols" not in ckpt:
        raise ValueError("Graphormer checkpoint does not contain spectrum_cols.")

    cols = [str(c) for c in ckpt["spectrum_cols"]]
    missing = [c for c in cols if c not in df.columns]

    if not missing:
        return cols

    # Fallback for columns stored as floats such as '400.0'.
    rename_map = {}
    df_cols_stripped = {str(c).strip(): c for c in df.columns}
    resolved = []
    still_missing = []

    for c in cols:
        if c in df.columns:
            resolved.append(c)
            continue

        alt_float = str(float(c)) if str(c).replace(".", "", 1).isdigit() else None
        alt_int = str(int(float(c))) if str(c).replace(".", "", 1).isdigit() else None

        found = None
        for alt in [alt_int, alt_float]:
            if alt is not None and alt in df_cols_stripped:
                found = df_cols_stripped[alt]
                break

        if found is None:
            still_missing.append(c)
        else:
            resolved.append(found)

    if still_missing:
        raise ValueError(
            f"IR CSV is missing spectrum columns required by checkpoint. "
            f"First missing columns: {still_missing[:10]}"
        )

    return [str(c) for c in resolved]


